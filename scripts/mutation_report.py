"""Write the mutation report (spec 02) to stdout: make mutate sends it to reports/mutation.md.

Counts mutants by status from `mutmut results --all true`, then lists every survivor with its
diff (`mutmut show`) and its hand classification from reports/mutation_classes.json:
  equivalent    the mutant cannot change any result (explain why)
  gap           a real mistake the invariants miss (add an invariant with a new ID, or list as known)
  out of scope  a mistake outside what the invariants are meant to cover (explain)
A survivor without a classification, or whose mutated lines changed since it was classified
(stale), is marked for a human. No target score: the survivors are the result.
"""
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

CLASSES_FILE = Path("reports/mutation_classes.json")
CLASSES = ("equivalent", "gap", "out of scope")


def mutmut(*args):
    out = subprocess.run([sys.executable, "-m", "mutmut", *args], capture_output=True, text=True,
                         check=True)
    return out.stdout


def statuses():
    """{mutant name: status} for every mutant."""
    result = {}
    for line in mutmut("results", "--all", "true").splitlines():
        if ":" in line and line.startswith("    "):
            name, status = line.strip().rsplit(": ", 1)
            result[name] = status
    return result


def changed_lines(diff):
    """The diff's - and + lines: what a classification was judged on."""
    return [ln for ln in diff.splitlines()
            if ln[:1] in "+-" and not ln.startswith(("+++", "---"))]


def main():
    status = statuses()
    counts = Counter(status.values())
    classes = json.loads(CLASSES_FILE.read_text(encoding="utf-8")) if CLASSES_FILE.exists() else {}
    survivors = sorted(n for n, s in status.items() if s == "survived")
    version = mutmut("--version").strip()

    print("# Mutation testing of the reference")
    print()
    print(f"Generated by `scripts/mutation_report.py` ({version}). Mutated: `statics.py`, `model.py`.")
    print("Runner: `pytest tests/test_physics.py -x -q` only, so each mutant is a mistake shared by")
    print("reference and port that parity would never see (spec 02). mutmut mutates code inside")
    print("functions only; module-level constants and PARAMS are not mutated. No target score: the")
    print("survivors are the result.")
    print()
    print("| status | mutants |")
    print("|---|---|")
    print(f"| all | {len(status)} |")
    for s in ("killed", "survived", "timeout"):
        print(f"| {s} | {counts.get(s, 0)} |")
    for s, n in sorted(counts.items()):
        if s not in ("killed", "survived", "timeout"):
            print(f"| {s} | {n} |")
    by_class = Counter()
    todo = 0
    blocks = []
    for name in survivors:
        diff = mutmut("show", name).split("\n", 1)[1].strip()
        entry = classes.get(name)
        if entry is None:
            verdict = f"UNCLASSIFIED: choose one of {', '.join(CLASSES)}, and explain"
            todo += 1
        elif entry.get("lines") != changed_lines(diff):
            verdict = f"STALE (the code changed since it was classified as {entry['class']}): classify again"
            todo += 1
        else:
            by = f" ({entry['by']})" if entry.get("by") else ""
            verdict = f"**{entry['class']}**{by}: {entry['why']}"
            by_class[entry["class"]] += 1
        blocks.append(f"### `{name}`\n\n```diff\n{diff}\n```\n\n{verdict}\n")
    untested = Counter(n.split("__mutmut_")[0] for n, s in status.items() if s == "no tests")
    if untested:
        print()
        print("## Not reached by the runner")
        print()
        print(f"{sum(untested.values())} mutants sit in functions `tests/test_physics.py` never calls. They")
        print("are reached by the parity and oracle tests, which spec 02 keeps out of this runner on")
        print("purpose (a shared mistake passes parity). Out of scope here, by function:")
        print()
        for fn, k in sorted(untested.items()):
            print(f"- `{fn.replace('.x_', '.')}`: {k}")
    print()
    summary = ", ".join(f"{by_class[c]} {c}" for c in CLASSES)
    print(f"## Survivors ({len(survivors)}: {summary}; {todo} to classify)")
    print()
    print("\n".join(blocks) if blocks else "None.")


if __name__ == "__main__":
    main()
